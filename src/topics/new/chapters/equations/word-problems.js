      steps: [`נסמן ב-[[x]] את הרוחב. האורך הוא [[x + ${k}]].`, `המשוואה (היקף): [[2 * (x + x + ${k}) = ${P}]]`, `[[4x + ${2 * k} = ${P}]], לכן [[4x = ${P - 2 * k}]] ו-[[x = ${x}]]`, `תשובה: הרוחב ${x} ס״מ והאורך ${x + k} ס״מ.`],
