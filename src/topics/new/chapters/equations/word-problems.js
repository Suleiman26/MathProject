const fromList = (list, tag) => (R) => { for (;;) { const q = R.pick(list)(R); if (q) return { tag, ...q }; } };

const linear = {
  id: 'linear-story',
  make: fromList(LINEAR, TAG),
  verify(q) {
    const d = q.data; const [x] = answers(q);
    if (!hasAll(q, d.nums)) return 'a number of the story is missing in the text';
    if (!(x > 0)) return 'answer must be positive';
    switch (d.kind) {
      case 'number': return d.a * x + d.b === d.c ? true : 'number story fails';
      case 'age-diff': return x + (x + d.d) === d.S ? true : 'ages fail';
      case 'age-times': return x + d.k * x === d.S ? true : 'ages fail';
      case 'savings': return d.a + d.b * x === d.c + d.d * x && d.b !== d.d ? true : 'savings fail';
      case 'consecutive': return x + (x + 1) + (x + 2) === d.S ? true : 'consecutive fail';
      default: return 'unknown kind';
    }
  },
};

/* ── 2. geometry ──────────────────────────────────────────────────────────── */
