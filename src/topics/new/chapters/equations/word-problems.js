      steps: ['נסמן ב-[[x]] את המספר הקטן. שני המספרים האחרים הם [[x + 1]] ו-[[x + 2]].', `המשוואה: [[x + x + 1 + x + 2 = ${S}]]`, `[[3x + 3 = ${S}]], לכן [[3x = ${S - 3}]] ו-[[x = ${x}]]`, `תשובה: המספר הקטן הוא ${x} (המספרים הם ${x}, ${x + 1}, ${x + 2}).`],
