      text: `האורך של מלבן גדול מהרוחב שלו ב-${k} ס״מ. היקף המלבן הוא ${P} ס״מ.\nמצאו את הרוחב ואת האורך של המלבן.`,
      rows: [{ label: 'הרוחב:', parts: [{ ans: x }, { t: 'ס״מ' }] }, { label: 'האורך:', parts: [{ ans: x + k }, { t: 'ס״מ' }] }],
