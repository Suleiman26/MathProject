function tokenize(src) {
  const s = String(src == null ? '' : src)
    .replace(/[‎‏‪-‮⁦-⁩]/g, '')
    .replace(/[−–—‒﹣－]/g, '-')
    .replace(/[×·⋅∙*✕]/g, '*')
    .replace(/[÷:\/∕]/g, '/')
    .replace(/[Xх]/g, 'x')
    .replace(/\s+/g, ' ')
    .trim();
  if (!s) return { err: 'empty' };
  if (/=/.test(s)) return { err: 'equals' };
  const out = [];
  let i = 0;
  while (i < s.length) {
    const c = s[i];
    if (c === ' ') { out.push({ t: ' ' }); i++; continue; }
    if (/\d/.test(c) || (c === '.' && /\d/.test(s[i + 1] || ''))) {
      let j = i;
      while (j < s.length && /\d/.test(s[j])) j++;
      if (s[j] === '.' && /\d/.test(s[j + 1] || '')) { j++; while (j < s.length && /\d/.test(s[j])) j++; }
      if (s[j] === '.') return { err: 'syntax' };
      out.push({ t: 'n', v: parseFloat(s.slice(i, j)) });
      i = j; continue;
    }
    if (c === 'x') { out.push({ t: 'x' }); i++; continue; }
    if ('+-*/()'.includes(c)) { out.push({ t: c }); i++; continue; }
    if (/[a-zA-Z֐-׿؀-ۿ]/.test(c)) return { err: 'letter' };
    return { err: 'char' };
  }
  // a space between two numbers ("2 3") is not a number; other spaces are just spacing
  const toks = [];
  for (let k = 0; k < out.length; k++) {
    if (out[k].t !== ' ') { toks.push(out[k]); continue; }
    const a = toks[toks.length - 1], b = out[k + 1];
    if (a && b && a.t === 'n' && b.t === 'n') return { err: 'syntax' };
  }
  return { toks };
}

/** parse("2x-20") → { ok: true, ast } or { ok: false, err: <key of ERR> } */
export function parse(src) {
  const tk = tokenize(src);
  if (tk.err) return { ok: false, err: tk.err };
  const toks = tk.toks;
  let p = 0;
  const peek = () => toks[p];
  class Bad extends Error { constructor(k) { super(k); this.k = k; } }
  function factor() {
    const t = peek();
    if (!t) throw new Bad('syntax');
    if (t.t === 'n') { p++; return { t: 'n', v: t.v }; }
    if (t.t === 'x') { p++; return { t: 'x' }; }
    if (t.t === '(') {
      p++;
      const e = expr();
      if (!peek() || peek().t !== ')') throw new Bad('paren');
      p++;
      return { t: 'grp', a: e };
    }
    if (t.t === ')') throw new Bad('paren');
    throw new Bad('syntax');
  }
  function unary() {
    const t = peek();
    if (t && t.t === '-') { p++; return { t: 'neg', a: unary() }; }
    if (t && t.t === '+') throw new Bad('syntax');
    return factor();
  }
  function term() {
    let a = unary();
    for (;;) {
      const t = peek();
      if (!t) break;
      if (t.t === '*' || t.t === '/') { p++; a = { t: t.t, a, b: unary() }; continue; }
      if (t.t === 'x' || t.t === '(') { a = { t: '*', a, b: factor(), imp: true }; continue; }
      if (t.t === 'n') throw new Bad('xnum'); // "x2", "(x+1)2"
      break;
    }
    return a;
  }
  function expr() {
    let a = term();
    for (;;) {
      const t = peek();
      if (!t || (t.t !== '+' && t.t !== '-')) break;
      p++;
      a = { t: t.t, a, b: term() };
    }
    return a;
  }
  try {
    const ast = expr();
    if (p < toks.length) throw new Bad(toks[p].t === ')' ? 'paren' : 'syntax');
    return { ok: true, ast };
  } catch (e) {
    if (e instanceof Bad) return { ok: false, err: e.k };
    throw e;
  }
}

export function evalAst(n, x) {
  switch (n.t) {
    case 'n': return n.v;
    case 'x': return x;
    case 'grp': return evalAst(n.a, x);
    case 'neg': return -evalAst(n.a, x);
    case '+': return evalAst(n.a, x) + evalAst(n.b, x);
    case '-': return evalAst(n.a, x) - evalAst(n.b, x);
    case '*': return evalAst(n.a, x) * evalAst(n.b, x);
    case '/': return evalAst(n.a, x) / evalAst(n.b, x);
  }
  return NaN;
}
export function hasX(n) { return n.t === 'x' || (!!n.a && hasX(n.a)) || (!!n.b && hasX(n.b)); }

// Not whole numbers on purpose: two different expressions almost never agree on all of them.
const POINTS = [1.37, 2.9, 5.11, 7.3, 11.83, 23.7, -3.41];
const close = (u, v) => Math.abs(u - v) <= 1e-7 * Math.max(1, Math.abs(u), Math.abs(v));
/** true when the two expressions give the same value for every x we try */
export function sameValue(a, b) {
  let seen = 0;
  for (const x of POINTS) {
    const u = evalAst(a, x), v = evalAst(b, x);
    if (!Number.isFinite(u) || !Number.isFinite(v)) { if (Number.isFinite(u) !== Number.isFinite(v)) return false; continue; }
    if (!close(u, v)) return false;
    seen++;
  }
  return seen >= 3;
}
function constDiff(a, b) {
  let d = null;
  for (const x of POINTS) {
    const u = evalAst(a, x) - evalAst(b, x);
    if (!Number.isFinite(u)) return false;
    if (d === null) d = u; else if (!close(u, d)) return false;
  }
  return d !== null && Math.abs(d) > 1e-9;
}
function dividesByZero(n) {
  if (n.t === '/' ) { const b = n.b; if (!hasX(b) && Math.abs(evalAst(b, 1)) < 1e-12) return true; }
  return (!!n.a && dividesByZero(n.a)) || (!!n.b && dividesByZero(n.b));
}
const must = (s) => { const r = parse(s); if (!r.ok) throw new Error('bad expression in a story: ' + s); return r.ast; };

/** Check one typed answer.
    part = { label, ans, traps: [[expr, hint]], hint }, others = the exercise's other parts.
    → { ok: true } | { ok: false, msg, format: true (not a real try) } | { ok: false, msg } */
export function check(input, part, others = []) {
  const r = parse(input);
  if (!r.ok) return { ok: false, format: true, msg: ERR[r.err] };
  if (dividesByZero(r.ast)) return { ok: false, format: true, msg: ERR.zero };
  const ans = must(part.ans);
  if (sameValue(r.ast, ans)) return { ok: true };
  if (!hasX(r.ast)) return { ok: false, msg: 'בביטוי חייב להופיע הנעלם [[x]]: עדיין לא יודעים כמה הוא שווה.' };
  for (const [e, hint] of part.traps || []) if (sameValue(r.ast, must(e))) return { ok: false, msg: hint };
  for (const o of others) if (o !== part && sameValue(r.ast, must(o.ans))) return { ok: false, msg: `זה הביטוי של "${o.label}". כאן מבקשים את "${part.label}".` };
  if (constDiff(r.ast, ans)) return { ok: false, msg: 'החלק עם [[x]] נכון. בדקו שוב את המספר שמוסיפים או מחסירים.' };
  return { ok: false, msg: part.hint || 'קראו שוב את הסיפור: מה קורה ל-[[x]] בכל שלב?' };
}

