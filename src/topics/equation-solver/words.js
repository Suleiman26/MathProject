function tools(r) {
  const int = (a, b) => a + Math.floor(r() * (b - a + 1));
  const pick = (arr) => arr[Math.floor(r() * arr.length)];
  const people = (n) => {
    const out = [];
    while (out.length < n) {
      const f = r() < 0.5;
      const name = pick(f ? GIRLS : BOYS);
      if (!out.some((p) => p.n === name)) out.push({ n: name, f });
    }
    return out;
  };
  return { int, pick, people };
}

