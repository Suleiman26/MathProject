/* "From words to an algebraic expression" (fixes board #70, Sulaiman).
   Pure logic, no React: a small safe expression parser (no eval), a checker that
   compares by VALUE (any equivalent form is accepted), and ~50 story templates.
   Tests: node --test src/topics/equation-solver/words.test.mjs

   Text convention: math inside Hebrew text is written as [[2x-20]]; the page draws it
   left-to-right (fractions stacked). plain() turns it into simple text. */

/* ── Parser ───────────────────────────────────────────────────────────────
   expr   := term (('+' | '-') term)*
   term   := unary (('*' | '/') unary | implicit-factor)*
   unary  := '-' unary | factor
   factor := number | x | '(' expr ')'
   Implicit multiplication: 2x, 3(x+1), (x+1)(x+2), x(x+5). Not allowed: x2, (x+1)2. */
