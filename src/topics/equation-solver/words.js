/** One story from a template (index or id). r = a random source like Math.random. */
export function makeStory(which, r = Math.random) {
  const t = typeof which === 'number' ? TEMPLATES[which] : TEMPLATES.find((x) => x[0] === which);
  const s = t[2](tools(r));
  return { id: t[0], tag: t[1], text: s.text, parts: s.parts, xr: s.xr };
}

/** Endless stories: every template once in a mixed order, then again in a new order.
    Never the same template twice in a row, and neighbours avoid the same tag. */
export function storyDeck(r = Math.random) {
  let queue = [], last = null;
  const refill = () => {
    const ids = TEMPLATES.map((_, i) => i);
    for (let i = ids.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [ids[i], ids[j]] = [ids[j], ids[i]]; }
    queue = ids;
  };
  return function next() {
    if (!queue.length) refill();
    let at = queue.findIndex((i) => !last || (TEMPLATES[i][0] !== last[0] && TEMPLATES[i][1] !== last[1]));
    if (at < 0) at = queue.findIndex((i) => !last || TEMPLATES[i][0] !== last[0]);
    if (at < 0) at = 0;
    const [i] = queue.splice(at, 1);
    last = TEMPLATES[i];
    return makeStory(i, r);
  };
}
