#!/usr/bin/env python3
"""Move each HTML topic into the Next.js app, without touching its logic.

Source : public/classic/<topic>.html   (the plain-HTML version, tag html-v1)
Output : src/topics/<slug>/Topic.jsx    Sulaiman's code, byte-for-byte, plus
                                        3 import lines on top and one export
                                        line at the bottom. The only line
                                        removed is the old
                                        ReactDOM.createRoot(...).render(<App/>)
         src/topics/<slug>/styles.js    the page's own CSS (as a string), so it
                                        is only on screen while that topic is
         src/topics/registry.js         list of topics (slug, title, colour)

Run again any time: python3 tools/convert-topics.py  (overwrites the output)
Then prove it:      python3 tools/verify-logic.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "public" / "classic"
OUT = ROOT / "src" / "topics"

BABEL = re.compile(r'<script type="text/babel"[^>]*>([\s\S]*?)</script>')
RENDER = re.compile(r"^ReactDOM\.createRoot\(document\.getElementById\('root'\)\)\.render\(<App ?/>\);[ \t]*$", re.M)
HEADER = (
    "'use client';\n"
    "/* eslint-disable */\n"
    "// Topic code by Sulaiman, copied unchanged from public/classic/{file}\n"
    "// (tools/verify-logic.py proves it). Added: these lines + the export at the end.\n"
    "// Removed: the old ReactDOM.createRoot(...).render(<App/>) line.\n"
    "import React from 'react';\n"
    "import ReactDOM from 'react-dom';\n"
    "// ===== BEGIN ORIGINAL =====\n"
)
FOOTER = "// ===== END ORIGINAL =====\nexport default App;\n"


def convert(html_path: Path):
    html = html_path.read_text(encoding="utf-8")
    blocks = BABEL.findall(html)
    if len(blocks) != 1:
        return None
    code = blocks[0]
    renders = RENDER.findall(code)
    assert len(renders) == 1, f"{html_path.name}: expected one render line, found {len(renders)}"
    body = RENDER.sub("", code, count=1)

    slug = html_path.stem
    title = re.search(r"<title>([\s\S]*?)</title>", html).group(1).strip()
    topic = re.search(r'<html[^>]*data-topic="([a-z]+)"', html)
    styles = re.findall(r"<style(?: id=\"mp-page\")?>([\s\S]*?)</style>", html)
    css = "\n".join(s.strip() for s in styles)

    d = OUT / slug
    d.mkdir(parents=True, exist_ok=True)
    existing = d / "Topic.jsx"
    if existing.exists() and "--force" not in sys.argv:
        m = re.search(r"// ===== BEGIN ORIGINAL =====\n([\s\S]*)// ===== END ORIGINAL =====\n", existing.read_text(encoding="utf-8"))
        if not m or m.group(1) != body:
            print(f"  ! {slug}: Topic.jsx was edited after the move. Kept as is (use --force to overwrite).")
            return {"slug": slug, "file": html_path.name, "title": title, "topic": topic.group(1) if topic else "teal"}
    (d / "Topic.jsx").write_text(HEADER.format(file=html_path.name) + body + FOOTER, encoding="utf-8")
    (d / "styles.js").write_text(
        "// The topic's own CSS (from public/classic/" + html_path.name + "), shown only while the topic is open.\n"
        "const css = " + json.dumps(css, ensure_ascii=False) + ";\nexport default css;\n",
        encoding="utf-8")
    return {"slug": slug, "file": html_path.name, "title": title, "topic": topic.group(1) if topic else "teal"}


def main():
    topics = []
    for f in sorted(SRC.glob("*.html")):
        r = convert(f)
        if r:
            topics.append(r)
            print(f"{r['slug']:22} {r['topic']:7} {r['title']}")
    loaders = ",\n".join(f"  {json.dumps(t['slug'])}: () => import('./{t['slug']}/Topic.jsx')" for t in topics)
    styles = ",\n".join(f"  {json.dumps(t['slug'])}: () => import('./{t['slug']}/styles.js')" for t in topics)
    meta = ",\n".join(f"  {json.dumps(t['slug'])}: {json.dumps({k: t[k] for k in ('title', 'topic', 'file')}, ensure_ascii=False)}" for t in topics)
    (OUT / "registry.js").write_text(
        "// Generated by tools/convert-topics.py. Do not edit by hand.\n"
        "export const TOPICS = {\n" + meta + "\n};\n\n"
        "export const LOADERS = {\n" + loaders + "\n};\n\n"
        "export const STYLES = {\n" + styles + "\n};\n",
        encoding="utf-8")
    print(len(topics), "topics")


if __name__ == "__main__":
    main()
